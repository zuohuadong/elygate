//#region src/lib/keyboard.svelte.ts
var KeyboardShortcuts = class {
	shortcuts = [];
	enabled = true;
	constructor() {
		if (typeof window !== "undefined") window.addEventListener("keydown", this.handleKeyDown.bind(this));
	}
	handleKeyDown(e) {
		if (!this.enabled) return;
		if (e.target.tagName === "INPUT" || e.target.tagName === "TEXTAREA") return;
		for (const shortcut of this.shortcuts) {
			const ctrlMatch = shortcut.ctrl ? e.ctrlKey || e.metaKey : true;
			const metaMatch = shortcut.meta ? e.metaKey : true;
			const shiftMatch = shortcut.shift ? e.shiftKey : true;
			const altMatch = shortcut.alt ? e.altKey : true;
			const keyMatch = e.key.toLowerCase() === shortcut.key.toLowerCase();
			if (ctrlMatch && metaMatch && shiftMatch && altMatch && keyMatch) {
				e.preventDefault();
				shortcut.callback();
				return;
			}
		}
	}
	register(shortcut) {
		this.shortcuts.push(shortcut);
		return () => {
			this.shortcuts = this.shortcuts.filter((s) => s !== shortcut);
		};
	}
	registerMultiple(shortcuts) {
		shortcuts.forEach((s) => this.register(s));
	}
	disable() {
		this.enabled = false;
	}
	enable() {
		this.enabled = true;
	}
	getShortcuts() {
		return [...this.shortcuts];
	}
};
new KeyboardShortcuts();
