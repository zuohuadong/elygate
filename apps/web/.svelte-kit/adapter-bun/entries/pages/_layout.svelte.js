//#region src/lib/theme.svelte.ts
function createThemeStore() {
	let theme = "light";
	function init() {}
	function applyTheme(t) {}
	function toggle() {
		theme = theme === "light" ? "dark" : "light";
		applyTheme(theme);
	}
	function set(t) {
		theme = t;
		applyTheme(theme);
	}
	return {
		get value() {
			return theme;
		},
		init,
		toggle,
		set
	};
}
createThemeStore();
